-- =========================================================
-- QCare Database Schema
-- PostgreSQL / Supabase
-- Berisi struktur 8 tabel dan relasi foreign key.
-- Jalankan pada database PostgreSQL yang masih kosong.
-- =========================================================

-- 1. Tabel pasien
CREATE TABLE IF NOT EXISTS public.pasien (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_pasien varchar(100) NOT NULL,
    tanggal_lahir date,
    jenis_kelamin varchar(20),
    no_telepon varchar(20),
    alamat text,
    kategori_pasien varchar(50) NOT NULL,
    kebutuhan_khusus text,
    created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP
);

-- 2. Tabel fasilitas kesehatan
CREATE TABLE IF NOT EXISTS public.fasilitas_kesehatan (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_fasilitas varchar(150) NOT NULL UNIQUE,
    jenis_fasilitas varchar(50),
    alamat text,
    no_telepon varchar(20),
    email varchar(100),
    created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP
);

-- 3. Tabel layanan
CREATE TABLE IF NOT EXISTS public.layanan (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fasilitas_id integer NOT NULL,
    nama_layanan varchar(100) NOT NULL,
    deskripsi text,
    estimasi_durasi integer,
    biaya decimal(12,2),
    aktif boolean DEFAULT true,
    CONSTRAINT fk_layanan_fasilitas
        FOREIGN KEY (fasilitas_id)
        REFERENCES public.fasilitas_kesehatan(id)
);

-- 4. Tabel dokter
CREATE TABLE IF NOT EXISTS public.dokter (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fasilitas_id integer NOT NULL,
    nama_dokter varchar(100) NOT NULL,
    spesialisasi varchar(100),
    no_telepon varchar(20),
    aktif boolean DEFAULT true,
    CONSTRAINT fk_dokter_fasilitas
        FOREIGN KEY (fasilitas_id)
        REFERENCES public.fasilitas_kesehatan(id)
);

-- 5. Tabel admin
CREATE TABLE IF NOT EXISTS public.admin (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_admin varchar(100) NOT NULL,
    email varchar(100) NOT NULL UNIQUE,
    password_hash text NOT NULL,
    role varchar(30),
    created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP
);

-- 6. Tabel jadwal dokter
CREATE TABLE IF NOT EXISTS public.jadwal_dokter (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dokter_id integer NOT NULL,
    layanan_id integer NOT NULL,
    hari varchar(15) NOT NULL,
    jam_mulai time NOT NULL,
    jam_selesai time NOT NULL,
    kuota integer,
    aktif boolean DEFAULT true,
    CONSTRAINT fk_jadwal_dokter_dokter
        FOREIGN KEY (dokter_id)
        REFERENCES public.dokter(id),
    CONSTRAINT fk_jadwal_dokter_layanan
        FOREIGN KEY (layanan_id)
        REFERENCES public.layanan(id)
);

-- 7. Tabel antrean
CREATE TABLE IF NOT EXISTS public.antrean (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pasien_id integer,
    fasilitas_id integer,
    layanan_id integer,
    dokter_id integer,
    jadwal_dokter_id integer,
    admin_id integer,
    nomor_antrean varchar(20) NOT NULL,